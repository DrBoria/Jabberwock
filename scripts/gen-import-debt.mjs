#!/usr/bin/env node
/**
 * gen-import-debt.mjs — regenerate the import-ban debt lists from the SOURCE, not from memory.
 *
 * Two bans are enforced with core ESLint `no-restricted-imports`, which cannot consult the generic
 * rule ledger (it is not a custom rule). Their grandfathered files are therefore derived here:
 *
 *   1. v3 plan B6 — `@jabberwock/types` must not depend on zod.
 *   2. v4 §1.3a — the backend app layer (actions / handlers / events) must be provider-agnostic:
 *      no LLM SDK imports outside the provider layer.
 *
 * The output is DATA (`debt/import-debt.js`), regenerated from what the tree actually contains. A
 * hand-written list of paths inside a rule is exactly what this replaces: it silently stops
 * matching the moment the code moves on. Both lists may only SHRINK — the ledger guard enforces it.
 *
 * Usage: node scripts/gen-import-debt.mjs [--dry-run]
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const OUT_PATH = path.join(ROOT, "packages", "config-eslint", "debt", "import-debt.js")
const DRY_RUN = process.argv.includes("--dry-run")

const SKIP_DIRS = new Set(["node_modules", "dist", "build", "out", ".turbo", ".next", "coverage"])

function walk(dir, out = []) {
	let entries
	try {
		entries = readdirSync(dir, { withFileTypes: true })
	} catch {
		return out
	}
	for (const e of entries) {
		if (SKIP_DIRS.has(e.name)) continue
		const p = path.join(dir, e.name)
		if (e.isDirectory()) walk(p, out)
		else if (/\.tsx?$/.test(e.name) && !e.name.endsWith(".d.ts")) out.push(p)
	}
	return out
}

const importsOf = (file) => {
	const src = readFileSync(file, "utf8")
	const out = new Set()
	for (const m of src.matchAll(/(?:from\s+|import\s*\(\s*|require\s*\(\s*)["']([^"']+)["']/g)) out.add(m[1])
	return out
}

// ── 1. zod inside @jabberwock/types ──────────────────────────────────────────
const typesDir = path.join(ROOT, "packages/types")
const zodDebt = walk(path.join(typesDir, "src"))
	.filter((f) => importsOf(f).has("zod"))
	.map((f) => path.relative(typesDir, f).replace(/\\/g, "/"))
	.sort()

// ── 2. provider SDKs in the backend APP layer (actions / handlers / events) ──
const PROVIDER_SDKS = [
	"@anthropic-ai/sdk",
	"openai",
	"@google/genai",
	"ollama",
	"@mistralai/mistralai",
	"@aws-sdk/client-bedrock",
	"@anthropic-ai/vertex",
]
const backendDir = path.join(ROOT, "backend")
const APP_LAYER = /^(features|services)\/.+\/(actions|handlers|events)\//
const providerSdkDebt = walk(backendDir)
	.map((f) => path.relative(backendDir, f).replace(/\\/g, "/"))
	.filter((rel) => APP_LAYER.test(rel))
	.filter((rel) => {
		const imports = importsOf(path.join(backendDir, rel))
		return PROVIDER_SDKS.some((sdk) => imports.has(sdk))
	})
	.sort()

const render = (name, list, note) =>
	`/**\n * ${note}\n * Generated by scripts/gen-import-debt.mjs — do not edit. Only shrinks.\n *\n * @type {string[]}\n */\nexport const ${name} = [\n${list.map((f) => `\t"${f}",`).join("\n")}\n]`

const contents = `/**
 * MACHINE-GENERATED import-ban debt.
 *
 * Both lists are DERIVED from the actual source tree by \`scripts/gen-import-debt.mjs\`. They exist
 * because two bans use core ESLint \`no-restricted-imports\` (which cannot use the generic rule
 * ledger), and a hand-maintained list of paths in a rule is precisely what we are removing: it
 * stops matching as soon as the code moves. Regenerate with \`pnpm import-debt\`; the ledger guard
 * fails the build if either list GROWS.
 */

${render("zodDebt", zodDebt, "Files in @jabberwock/types that still import zod (v3 plan B6).")}

${render(
	"providerSdkDebt",
	providerSdkDebt,
	"Backend app-layer files (actions/handlers/events) that still import an LLM SDK (v4 §1.3a).",
)}
`

if (DRY_RUN) {
	console.log(`gen-import-debt (dry run): zod ${zodDebt.length}, provider-sdk ${providerSdkDebt.length}`)
	process.exit(0)
}

writeFileSync(OUT_PATH, contents)
console.log(`gen-import-debt: wrote ${path.relative(ROOT, OUT_PATH)}`)
console.log(`  zodDebt: ${zodDebt.length}   providerSdkDebt: ${providerSdkDebt.length}`)
